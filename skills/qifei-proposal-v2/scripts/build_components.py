#!/usr/bin/env python3
"""Compile the text-layer components of DESIGN.md into one shared stylesheet, deck/components.css.

Every page links it (review_hooks.py inject adds the link) and uses its classes instead of its own
font sizes and Logo placement, so a change in design-tokens.json reaches every page at once.

usage: python3 scripts/build_components.py <project>
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

OUT = "deck/components.css"


def css_name(level: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", level.lower()).strip("-")


def build(tokens: dict) -> str:
    scale = tokens.get("type_scale") if isinstance(tokens.get("type_scale"), dict) else {}
    if not scale:
        raise ValueError("design-tokens.json has no type_scale; compile DESIGN.md's type table first")
    fonts = tokens.get("fonts") if isinstance(tokens.get("fonts"), dict) else {}
    colors = tokens.get("colors") if isinstance(tokens.get("colors"), dict) else {}
    logo = tokens.get("logo") if isinstance(tokens.get("logo"), dict) else {}
    slot = logo.get("slot") if isinstance(logo.get("slot"), dict) else {}
    lines = [
        "/* Generated by build_components.py from deck/design-tokens.json. Do not edit by hand. */",
        ":root {",
    ]
    for level, spec in scale.items():
        name = css_name(level)
        lines.append(f"  --q-{name}-size: {spec['px']}px;")
        lines.append(f"  --q-{name}-leading: {spec.get('line_height', 1.3)};")
    if fonts.get("display"):
        lines.append(f"  --q-font-display: {fonts['display']};")
    if fonts.get("body"):
        lines.append(f"  --q-font-body: {fonts['body']};")
    for key in ("text", "muted", "accent"):
        if colors.get(key):
            lines.append(f"  --q-{key}: {colors[key]};")
    lines.append("}")
    for level in scale:
        name = css_name(level)
        family = "var(--q-font-display, inherit)" if name in {"hero", "title", "statement", "cover", "chapter"} else "var(--q-font-body, inherit)"
        lines.append(f".q-{name} {{ font-size: var(--q-{name}-size); line-height: var(--q-{name}-leading); font-family: {family}; }}")
    if {"x", "y", "w"} <= set(slot):
        lines.append(f".q-logo {{ position: absolute; left: {slot['x']}px; top: {slot['y']}px; width: {slot['w']}px; height: auto; }}")
    lines.append(".q-source { color: var(--q-muted, inherit); }")
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    project = Path(sys.argv[1]).expanduser().resolve()
    tokens = json.loads((project / "deck" / "design-tokens.json").read_text(encoding="utf-8"))
    try:
        css = build(tokens)
    except (ValueError, KeyError, TypeError) as error:
        print(f"FAIL: {error}")
        return 1
    out = project / OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(css, encoding="utf-8")
    levels = ", ".join(f".q-{css_name(level)}" for level in tokens["type_scale"])
    print(f"Wrote {OUT}: {levels}" + (", .q-logo" if (tokens.get("logo") or {}).get("slot") else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
